client = genai.Client(api_key = key)

# Incident triage is the rapid assessment step where IT and operations teams determine the scope, severity, and ownership of a new incident before active resolution begins.

def triage_incident(raw_complaint):

  #detailed system instruction which has persona, task and output format
  system_blueprint = """
    You are an automated cloud server triage engine.
    Extract data into this exact schema:
    System: [Database, Frontend, Network, or Unknown]
    Severity: [High, Medium, Low]
    Action: [Restart, Scale, Patch, or Investigate]

    EXAMPLE:
    Input: "Our database connection pool is exhausted! 500 errors."
    Output: System: Database | Severity: High | Action: Restart
    """

  try:
    response = client.models.generate_content(

            model="gemini-3.1-flash-lite",
            contents=f"Alert Text: <{raw_complaint}>",

            #parameter tuning
            config=types.GenerateContentConfig(
                system_instruction=system_blueprint,
                temperature=0.0,
                max_output_tokens=250,
                http_options=types.HttpOptions(timeout=15000)
            )
        )
    #removing extra spaces
    raw_output = response.text.strip()

    #final output when the code runs successfully
    return {"status": "Success", "payload": raw_output,
                "tokens": response.usage_metadata.total_token_count}

  except errors.APIError as e:
      return {"status": "Pipeline Error", "payload": str(e.message), "tokens": 0}

  except Exception as e:
      return {"status": "Pipeline Error", "payload": str(e), "tokens": 0}

result = triage_incident("The login page loads, but clicking the Sign In button does nothing")

print(result)



import time

def resilient_triage_orchestrator(complaint_text, max_retries=3):
    print("--- STARTING TRIAGE ---")

    for attempt in range(1, max_retries + 1):
        print(f"Attempt {attempt} of {max_retries}...")
        report = triage_incident(complaint_text)

        if report["status"] == "Success":
            print("Success!")
            return report

        print(f"Attempt {attempt} failed. Retrying in 2 seconds...")
        time.sleep(2)

    print("All retries used up without success.")
    return report

