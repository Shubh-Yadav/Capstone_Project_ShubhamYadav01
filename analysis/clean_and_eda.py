from google.genai import types, errors

def translate_text(text_to_translate, target_language):

  try:
    response = client.models.generate_content(
      model="gemini-3-flash-preview",
      contents=text_to_translate,
      config=types.GenerateContentConfig(
        system_instruction=f"Translate this into {target_language}. Keep the same feeling. Reply with only the text."
      )
    )
    return {"status":"Success",
      "data": response.text,
      "tokens_used": response.usage_metadata.total_token_count}

  except errors.APIError as e:
    return {"status":"Error","data":e.message,"tokens_used":0}

